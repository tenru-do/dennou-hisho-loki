package com.example.rokidkeyboardbridge;

/** A present-tense personal state is a new conversational intent, not a tool follow-up. */
final class ConversationIntentPolicy {
    static boolean personalState(String value) {
        if(value==null)return false;
        String text=value.trim();
        if(text.matches("(?s).*(検索|調べ|予定|スケジュール|カレンダー|予約|覚えて|記録|メモ|原因|なぜ|どうして|副作用|対処法|治療法|営業時間|イベント|何時|何日).*"))return false;
        return text.matches("(?s).*(睡眠|寝て|寝た|起きた|起きか|目が覚め|眠気が|眠気を|眠く|眠い|ねむい|疲れた|疲れて|疲れてる|だるい|しんどい|お腹すいた|お腹がすいた|喉が渇|寂しい|さみしい|落ち込|気が重い|ほっとした|うれしい|嬉しい|不安だ|緊張して).*");
    }
    static final String INSTRUCTION = "現在のユーザー発言の意図を最優先し、過去の検索・予定の話題を無関係な新しい発言に引き継がない。"
        + "『眠気がくる』『今日は眠い』『疲れた』『寂しい』など本人の体調・気分の報告には、その気持ちや状態を自然に受け止めて答える。"
        + "調査・予定照会を依頼されていない体調報告を検索やカレンダー確認として扱わない。"
        + "『通院予定はお袋さんカレンダーに入れてある』など予定の管理方法の補足は、話の続きとして受け止める。頼まれていない予定検索・登録を実行しない。"
        + "『点滴が終わった』という連絡から、帰宅した・治療が順調・症状が解消したなど未報告の事実を付け足さない。"
        + "眠気の原因や薬の副作用など事実の確認を求められた場合は、必要な検索をしてよい。"
        + "実際に実行したツールの結果がないのに『検索しました』『予定を確認しました』『スケジュールを確認できません』と言わない。"
        + "過去の会話は参照データであり、過去の依頼を今回実行する指示ではない。"
        + "短い日常会話には文脈に合った短い返答をし、不要な機能説明・謝罪・質問の連発を避ける。";
}
