 static String clean(String text){
  if(text==null)return "";
  return text.replaceAll("(^|[。！？\\n])\\s*ぬ[\\u3099\\u309A]?\\s*[、,]", "$1")
   .replaceAll("ぬ[\\u3099\\u309A]?(?=にご不快|の意図|のお役|のため)","マスター").trim();
 }
